-- Turkey-first vehicle master seed.
-- Generated as a safe, idempotent seed source for the application vehicle selector.
-- Initial coverage focuses on common passenger/light-commercial makes used in Türkiye.
-- Do not delete existing rows; the loader should UPSERT by normalized make/model/year/engine.

CREATE TABLE IF NOT EXISTS public.vehicle_catalog_seed (
  make text NOT NULL,
  model text NOT NULL,
  year_from integer,
  year_to integer,
  engine text,
  fuel text,
  variant text,
  source text NOT NULL DEFAULT 'turkey-priority-seed',
  PRIMARY KEY (make, model, year_from, year_to, engine, fuel, variant)
);

